/* global console, process */
/**
 * Converts the team's event sheet export into src/shared/data/eventDatabase.js.
 *
 * The site does not import this file: the archive on genesishacks.com is
 * curated by hand in src/shared/data/events.js. This raw copy exists so the
 * curated list can be checked against the sheet.
 *
 * Privacy (audit D12): no URL from the sheet is ever written out. Attendee
 * columns sometimes held links to registration sheets with personal data,
 * and media columns hold private Drive and SharePoint folders. Both are
 * dropped; only plain attendee counts survive.
 *
 * Usage: node scripts/convert-csv.mjs
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const csvPath = path.join(__dirname, "../event-database/GENESIS EVENT DATABASE - Sheet1.csv");
const outputPath = path.join(__dirname, "../src/shared/data/eventDatabase.js");

const URL_PATTERN = /https?:\/\/\S+/i;

function parseLine(line) {
  const columns = [];
  let field = "";
  let quoted = false;
  for (const char of line) {
    if (char === '"') quoted = !quoted;
    else if (char === "," && !quoted) {
      columns.push(field.trim());
      field = "";
    } else field += char;
  }
  columns.push(field.trim());
  return columns;
}

/** Keep a value only if it holds no link. */
const clean = (value) => (URL_PATTERN.test(value || "") ? "" : (value || "").trim());

try {
  const lines = fs.readFileSync(csvPath, "utf-8").split(/\r?\n/);
  const events = [];

  for (const raw of lines.slice(1)) {
    const line = raw.trim();
    if (!line) continue;
    // Sr no. | EVENT NAME | EVENT DATE | EVENT LOCATION | EVENT TYPE | TOTAL ATTENDEES | EVENT MEDIA | EVENT SPONSERS
    const [srNo, name, date, location, type, attendees] = parseLine(line);
    const title = clean(name);
    if (!title || !srNo || title.includes("RANDOM DATA")) continue;
    const count = clean(attendees).replace(/[^\d]/g, "");

    events.push({
      id: srNo.padStart(2, "0"),
      title,
      date: clean(date),
      location: clean(location),
      category: clean(type) || "Meetup",
      attendees: count ? Number(count) : null,
    });
  }

  const js = `// Generated by scripts/convert-csv.mjs from the event sheet export.
// Not used by the site: the public archive lives in ./events.js.
// Links from the sheet (registration sheets, photo folders) are never copied here.
export const eventDatabase = ${JSON.stringify(events, null, 2)};
`;

  fs.writeFileSync(outputPath, js, "utf-8");
  console.log(`Wrote ${events.length} events to ${path.relative(process.cwd(), outputPath)}`);
} catch (err) {
  console.error("Error converting CSV:", err);
  process.exitCode = 1;
}
